print(add((1, 2, 3), (4, 5, 6)))
print(add.__doc__)

# ===========================================================
# 2. 튜플을 리턴하는 함수
# ===========================================================
def add_sub(a, b):
    return a + b, a - b
print(add_sub(10, 20))
print(*add_sub(10, 20))
x,y = add_sub(1, 2)
print(x, y)

# ===========================================================
# 3. 디폴트 매개변수 (Default Parameter)
# ===========================================================
# 매개변수에 기본값을 지정하면, 호출 시 해당 인자를 생략할 수 있다.
# 디폴트 매개변수는 항상 일반 매개변수 뒤에 위치해야 한다.
def sub(a=0,b=10):
    return a - b

print(sub(10, 20))
print(sub(10))
print(sub())

# ===========================================================
# 4. 키워드 인자 (Keyword Argument)
# ===========================================================
# 인자를 순서가 아니라 "매개변수명=값" 형태로 전달할 수 있다.
# 순서를 바꿔서 호출해도 이름만 맞으면 정확히 전달된다.
print(sub(5,10))
print(sub(b=10, a=5))

def introduce(name,hobby,place = "안산"):
    return f"안녕하세요. 저는 {place}에 사는 {name}입니다. 취미는 {hobby}입니다."
print(introduce("뽀로로", "놀기", "EBS"))
print(introduce(place="EBS", hobby="놀기", name="뽀로로"))
print(introduce(name = "뽀로로", hobby="놀기"))


# ===========================================================
# 5. 가변 인자 (Variable-length Argument, *args)
# ===========================================================
# 몇 개의 인자가 들어올지 모를 때 *args를 사용한다. (관례적으로 사용)
# args라는 이름으로 입력값들을 모아 튜플로 만든다.

def add_all(*args):
    print(args)
    return sum(args)
print(add_all(1,2,3))


# ================================================================
# 6. 키워드 가변 인자 (Keyword Variable-length Argument, **kwargs)
# ================================================================
# 이름=값 형태로 몇 개가 들어올지 모를 때 **kwargs를 사용한다.
# kwargs라는 이름으로 입력값들을 모아 딕셔너리로 만든다.

def introduce2(**kwargs):
    print(kwargs)

introduce2(name="뽀로로", age=4, kind="공룡")
d = {"name": "크롱", "age": 4, "kind": "공룡"}
introduce2(**d)

# ===========================================================
# 7. *args와 **kwargs를 함께 사용하는 예시
# ===========================================================

# 디미가 현재 가진 돈 구하기
# - 지난 달 남은 돈 : 500원
# - 길 가다가 주운 돈 : 100원, 200원 => 가변인자 (튜플)
# - 아빠한테 받은 돈 : 10000원
# - 엄마한테 받은 돈 : 5000원 => 키워드 가변인자 (딕셔너리)

def pocket_money(*args, **kwargs):
    total = sum(args)
    for value in kwargs.values():
        total += value
    return total

print(pocket_money(500, 100, 200, father=10000, mother=5000))